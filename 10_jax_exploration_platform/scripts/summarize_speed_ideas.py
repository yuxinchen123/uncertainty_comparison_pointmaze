"""Summarize the baseline and ten bounded speed measurements."""
import argparse
import json
from pathlib import Path


def main():
    """Publish measured speeds and resources, without claiming untested combined gains."""
    parser = argparse.ArgumentParser()
    parser.add_argument("benchmark_dir", type=Path)
    args = parser.parse_args()
    rows = [json.loads(path.read_text()) for path in sorted((args.benchmark_dir / "data").glob("*.json"))]
    if len(rows) != 11:
        raise ValueError(f"expected baseline plus ten ideas, found {len(rows)} measurements")
    if any(row["wall_seconds"] >= 600 for row in rows):
        raise ValueError("a speed idea exceeded its ten-minute budget")
    baseline = next(row for row in rows if row["idea"] == "baseline")
    rows.sort(key=lambda row: (row["idea"] != "baseline", row["idea"]))
    lines = ["Generated by scripts/summarize_speed_ideas.py from data/*.json.", "",
             "The corrected RND trainer was measured on serval05's H100 NVL, with full-batch "
             "updates, 128 rollout steps, four environments per copy, coverage enabled, and "
             "float64 running statistics. Each row includes compilation and three eight-second "
             "steady timing blocks. Every idea finished in under ten minutes of active execution.", "",
             "| Execution choice | Copies | Steps/s per copy | 100M steps (minutes) |",
             "|---|---:|---:|---:|"]
    for row in rows:
        lines.append(f"| {row['idea'].replace('_', ' ')} | {row['copies']} | "
                     f"{row['steps_per_second_per_copy']:,.0f} | "
                     f"{row['seconds_for_100_million_per_copy']/60:.2f} |")
    lines += ["", "The time estimates exclude setup. Smaller copy batches improve time per "
              "configuration while reducing the aggregate rate of one card. Independent settings "
              "can run on several available cards. Combining execution choices requires its own "
              "measurement; gains in these individual rows are not multiplied.", "",
              "| Execution choice | Aggregate steps/s | Setup (seconds) | Peak device memory (MiB) |",
              "|---|---:|---:|---:|"]
    for row in rows:
        lines.append(f"| {row['idea'].replace('_', ' ')} | {row['steps_per_second_total']:,.0f} | "
                     f"{row['build_prime_compile_seconds']:.1f} | {row['peak_device_memory_mb']:.1f} |")
    # Only a single measured change is chosen for each aspect; paired confirmation comes later.
    loop_rows = [row for row in rows if row["copies"] == 512 and not row["changes"].get("flat_params")]
    best = min(loop_rows, key=lambda row: row["seconds_per_iteration"])
    lines += ["", f"The fastest 512-copy loop measurement was {best['idea'].replace('_', ' ')}. "
              f"Its speed relative to the baseline was "
              f"{best['steps_per_second_per_copy']/baseline['steps_per_second_per_copy']:.3f}. "
              "Packed parameters were slower and are not retained. The corrected selected-run "
              "queue uses 128 copies per setting and keeps the same 128 seeds."]
    lines += ["", "The 32-iteration grouped-dispatch candidate was rejected after its longer "
              "numerical check: the final RND position differed by 0.00526, above the "
              "predeclared 2e-5 tolerance. It is absent from the production training entry. "
              "The retained changes are explicit parameter selection and 128-copy batches "
              "distributed through a shared queue; individual iteration execution is preserved."]
    (args.benchmark_dir / "analysis.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:19]), flush=True)


if __name__ == "__main__":
    main()
