"""Keep measurement reports faithful to completed, rejected, and incremental records."""

from datetime import datetime, timezone
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from performance_report import classify_records, render_report, write_report


def measured_record(name='baseline', completed=True):
    """Build a complete small four-case fixture with mutually consistent units."""
    # Eight copies advancing 128 transitions per iteration at 8000 total steps/second.
    cases = [{'policy_kind': policy, 'geometry': geometry, 'copies': 8,
              'completed': True, 'correctness': {'passed': True},
              'seconds_per_iteration': .128, 'steps_per_second_total': 8000,
              'steps_per_second_per_copy': 1000,
              'hours_per_million_steps_per_copy': 1_000_000/3_600_000,
              'build_compile_seconds': .2, 'peak_device_memory_mb': 42}
             for policy in ('tabular', 'neural') for geometry in ('straight', 'snake')]
    return {'idea': name, 'completed': completed, 'cases': cases, 'wall_seconds': 12}


class PerformanceReportTests(unittest.TestCase):
    """Reject invented rates and preserve in-progress records as unfinished."""

    def test_completed_measurement_has_four_groups_and_required_units(self):
        """Render measured timing and resource columns in every applicable group."""
        report = render_report([measured_record()], datetime(2026, 11, 1, tzinfo=timezone.utc))
        for policy in ('Tabular', 'Neural'):
            for geometry in ('straight', 'snake'):
                self.assertIn(f'## {policy} policy, {geometry} grid', report)
        self.assertEqual(report.count('Seconds per<br>iteration'), 4)
        self.assertEqual(report.count('per copy<br>(thousands)'), 4)
        self.assertIn('Build and<br>compilation', report)
        self.assertIn('12.00', report)
        self.assertIn('42.00', report)
        self.assertIn('2026-10-31 17:00 PT', report)
        self.assertIn('Generated by', report)

    def test_partial_record_without_failure_is_unfinished(self):
        """Incrementally published cases must never count as rejected measurements."""
        partial = measured_record('batch_random_key_derivation', completed=False)
        partial['cases'] = partial['cases'][:2]
        complete, rejected, unfinished = classify_records([partial])
        self.assertFalse(complete)
        self.assertFalse(rejected)
        self.assertEqual(len(unfinished), 1)
        report = render_report([partial])
        self.assertIn('Rejected: 0. In progress: 1.', report)
        self.assertIn('2 completed correct cases', report)

    def test_rejected_case_keeps_reason_and_excludes_partial_good_rates(self):
        """Do not report favorable completed subcases of a rejected global measurement."""
        rejected = measured_record('all_state_minibatch_predictions', completed=False)
        rejected['cases'][0]['steps_per_second_total'] = 9_999_000_000
        rejected['failure'] = ('correctness comparison failed:\nNot equal to tolerance rtol=2e-05\n'
            'floating state leaf 1\nMax absolute difference among violations: 3.25e-05\n'
            'ACTUAL: array([999, 999, 999])')
        report = render_report([measured_record(), rejected])
        self.assertIn('Rejected: 1.', report)
        self.assertIn('3.25e-05', report)
        self.assertNotIn('ACTUAL:', report)
        self.assertNotIn('9999.000', report)

    def test_inconsistent_per_copy_rate_is_rejected(self):
        """Prevent an aggregate rate from being presented as a per-copy rate."""
        invalid = measured_record()
        invalid['cases'][0]['steps_per_second_per_copy'] = 8000
        with self.assertRaisesRegex(ValueError, 'per-copy throughput disagree'):
            render_report([invalid])

    def test_write_report_reads_json_and_replaces_only_generated_output(self):
        """Run the standard-library publication path on synthetic incremental records."""
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root/'data/benchmarks').mkdir(parents=True)
            record_path = root/'data/benchmarks/baseline.json'
            record_path.write_text(json.dumps(measured_record(completed=False)))
            first = write_report(root)
            self.assertEqual(first['completed'], 0)
            self.assertEqual(first['in_progress'], 1)
            record_path.write_text(json.dumps(measured_record()))
            second = write_report(root)
            self.assertEqual(second['completed'], 1)
            self.assertEqual(second['in_progress'], 0)
            self.assertTrue((root/'analysis/infrastructure.md').exists())
            self.assertFalse((root/'analysis/infrastructure.md.temporary').exists())


if __name__ == '__main__':
    unittest.main()
