"""Render measured infrastructure results using only Python's standard library."""

import argparse
from datetime import datetime
import html
import json
import math
from pathlib import Path
import tempfile
import textwrap
from zoneinfo import ZoneInfo


def idea_label(name):
    """Keep the complete idea name readable within a printable table cell."""
    # Before: reuse_count_bonus_terms; after: reuse count bonus<br>terms.
    return '<br>'.join(html.escape(line) for line in textwrap.wrap(
        name.replace('_', ' '), width=24, break_long_words=False, break_on_hyphens=False))


def failure_summary(document):
    """Retain the numerical rejection reason without copying large array dumps."""
    # Preserve measured tolerances and differences, but omit repeated tensor contents.
    lines = str(document.get('failure', 'A recorded correctness comparison did not pass.')).splitlines()
    selected = [line.strip() for line in lines if line.strip() and (
        line == lines[0] or 'tolerance' in line or 'floating state leaf' in line
        or 'discrete state leaf' in line or line.startswith('Max absolute difference'))]
    return ' '.join(selected)


def classify_records(records):
    """Separate completed correct measurements from rejected and unfinished attempts."""
    complete, rejected, unfinished = [], [], []
    for record in records:
        cases = record.get('cases', [])
        correct = all(case.get('completed') and case.get('correctness', {}).get('passed')
                      for case in cases)
        if record.get('completed') and cases and correct:
            complete.append(record)
        elif record.get('failure') or record.get('correctness', {}).get('passed') is False:
            rejected.append(record)
        else:
            unfinished.append(record)
    return complete, rejected, unfinished


def checked_number(case, name, *, positive=True):
    """Require real finite measurements rather than filling missing values with guesses."""
    value = float(case[name])
    if not math.isfinite(value) or (value <= 0 if positive else value < 0):
        raise ValueError(f'{case.get("idea", "measurement")} has an invalid {name}')
    return value


def render_report(records, generated_at=None):
    """Render four policy/geometry groups and an independent resource/rejection record."""
    # Rank descriptive names consistently; no estimated combination gains are introduced.
    complete, rejected, unfinished = classify_records(records)
    ordering = lambda row: (row['idea'] != 'baseline', row['idea'])
    complete.sort(key=ordering)
    instant = generated_at or datetime.now().astimezone()
    displayed = instant.astimezone(ZoneInfo('America/Los_Angeles')).strftime('%Y-%m-%d %H:%M PT')
    lines = [
        '<!-- Generated by scripts/grid_initialization_campaign/performance_report.py. Do not edit by hand. -->',
        '# Infrastructure measurements', '',
        f'Updated {displayed}. Completed and correct: {len(complete)}. '
        f'Rejected: {len(rejected)}. In progress: {len(unfinished)}.', '',
        'Each row is an actual measurement. Every accepted measurement passed the recorded '
        'fixed-data optimizer and rollout comparisons. Combined execution choices appear only '
        'after the combination itself was measured.', '',
        'Total steps per second includes all copies. Per-copy steps per second divides that '
        'rate by the number of independent training copies. Hours per million steps is also '
        'per copy and excludes initialization and compilation.', '']

    # The required five timing columns are shown alongside the full literal idea name.
    for policy in ('tabular', 'neural'):
        for geometry in ('straight', 'snake'):
            lines += [f'## {policy.capitalize()} policy, {geometry} grid', '',
                '| Execution choice | Copies | Seconds per<br>iteration | Total steps per<br>second<br>(millions) | Steps per second<br>per copy<br>(thousands) | Hours per<br>million steps<br>per copy |',
                '|---|---:|---:|---:|---:|---:|']
            count = 0
            for record in complete:
                for case in record['cases']:
                    if (case['policy_kind'], case['geometry']) != (policy, geometry):
                        continue
                    copies = int(case['copies'])
                    if copies < 1:
                        raise ValueError('a measured copy count must be positive')
                    duration = checked_number(case, 'seconds_per_iteration')
                    total = checked_number(case, 'steps_per_second_total')
                    per_copy = checked_number(case, 'steps_per_second_per_copy')
                    hours = checked_number(case, 'hours_per_million_steps_per_copy')
                    if not math.isclose(total/copies, per_copy, rel_tol=1e-6):
                        raise ValueError('aggregate and per-copy throughput disagree')
                    if not math.isclose(1_000_000/(3600*per_copy), hours, rel_tol=1e-6):
                        raise ValueError('hours per million steps do not match the measured rate')
                    lines.append(f'| {idea_label(record["idea"])} | {copies} | {duration:.6f} | '
                        f'{total/1_000_000:.3f} | {per_copy/1000:.3f} | {hours:.4f} |')
                    count += 1
            if not count:
                lines += ['', 'No completed correct measurement is available for this group.']
            lines.append('')

    # Keep resource columns separate so the required timing table remains narrow.
    lines += ['## Compilation, execution time, and memory', '',
        'Build and compilation is the sum of each case’s initialization and first synchronized '
        'training iteration. Total wall time also includes correctness checks and all timing '
        'blocks. GPU memory is the process cumulative peak, including correctness checks and '
        'compiled programs; it is not an isolated training-array estimate.', '',
        '| Execution choice | Build and<br>compilation<br>(seconds) | Total wall<br>time<br>(seconds) | Peak GPU<br>memory<br>(MiB) |',
        '|---|---:|---:|---:|']
    for record in complete:
        compilation = sum(checked_number(case, 'build_compile_seconds', positive=False)
                          for case in record['cases'])
        peak = max(checked_number(case, 'peak_device_memory_mb', positive=False)
                   for case in record['cases'])
        wall = checked_number(record, 'wall_seconds')
        lines.append(f'| {idea_label(record["idea"])} | {compilation:.2f} | {wall:.2f} | {peak:.2f} |')

    # A failed global comparison never contributes a favorable partial case to the accepted rows.
    lines += ['', '## Rejected measurements', '']
    if rejected:
        for record in sorted(rejected, key=ordering):
            lines.append(f'- **{record["idea"].replace("_", " ")}**: '
                         +failure_summary(record).replace('|', '\\|'))
    else:
        lines.append('No recorded measurement has been rejected.')
    lines += ['', '## Measurements still in progress', '']
    if unfinished:
        for record in sorted(unfinished, key=ordering):
            checked = sum(bool(case.get('completed') and case.get('correctness', {}).get('passed'))
                          for case in record.get('cases', []))
            lines.append(f'- {record["idea"].replace("_", " ")}: {checked} completed correct cases; '
                         'the full measurement is unfinished.')
    else:
        lines.append('No measurement record is unfinished.')
    return '\n'.join(lines)+'\n'


def write_report(run_dir):
    """Regenerate the durable report from small JSON measurement records only."""
    run_dir = Path(run_dir)
    records = [json.loads(path.read_text())
               for path in sorted((run_dir/'data/benchmarks').glob('*.json'))]
    document = render_report(records)
    output = run_dir/'analysis/infrastructure.md'
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=output.parent,
                                     prefix=output.name+'.', delete=False) as handle:
        handle.write(document)
        temporary = Path(handle.name)
    temporary.replace(output)
    complete, rejected, unfinished = classify_records(records)
    return {'report': str(output), 'completed': len(complete),
            'rejected': len(rejected), 'in_progress': len(unfinished)}


def main():
    """Write a measurement report without importing a numerical runtime."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run-dir', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(write_report(args.run_dir)), flush=True)


if __name__ == '__main__':
    main()
