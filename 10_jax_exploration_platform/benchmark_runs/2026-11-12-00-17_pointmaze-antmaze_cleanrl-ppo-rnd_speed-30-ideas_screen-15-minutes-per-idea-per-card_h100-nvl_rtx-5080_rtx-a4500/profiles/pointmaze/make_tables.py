# idea number -> what the state comparison on the card found after ONE iteration (64 policies x 4
# environments). After 10 iterations (job 6874052) the same comparison finds differences of order 1
# in single environments' velocities for ideas 20 and 14: a rounding difference grows that far in
# this trainer, so a longer comparison of states says nothing; the 64-seed comparison decides.
ONE_ITERATION_ON_CARD = {
    20: "87 of 87 state arrays bit-identical",
    19: "87 of 87 state arrays bit-identical",
    14: "24 of 87 state arrays bit-identical, largest difference of the others 2.7e-06",
}
