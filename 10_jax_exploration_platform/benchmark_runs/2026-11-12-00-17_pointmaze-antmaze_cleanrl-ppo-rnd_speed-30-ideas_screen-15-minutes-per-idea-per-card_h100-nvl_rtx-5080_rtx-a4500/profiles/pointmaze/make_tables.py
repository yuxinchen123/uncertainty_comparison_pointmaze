"""Write the PointMaze tables of this speed study from the raw records beside this script.

Reads `time_breakdown/*.json` (one record per card, environments per policy and number of
policies, written by benchmarks/harness/profile_study_iteration_pieces.py) and `ideas/*.json` (one
record per idea and card, written by benchmarks/harness/compare_study_arms.py), and writes
`time_breakdown.md` and `idea_measurements.md` here. Standard library only.

Usage: python3 make_tables.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

# the rows of a breakdown table, in the order of the iteration; each is a piece's record name or
# a difference of records
UPDATE = "update (shuffle, gather, sixteen gradients, clip, Adam)"
GATHER = "shuffle and gather alone"
GRADIENTS = "sixteen gradients alone"
CLIPPED = "sixteen gradients with the clip"
ROWS = (
    ("update: all of it", lambda p: p[UPDATE]),
    ("update: sixteen gradients", lambda p: p[GRADIENTS]),
    ("update: gradient clip", lambda p: p[CLIPPED] - p[GRADIENTS]),
    ("update: shuffle and gather", lambda p: p[GATHER]),
    ("update: permutation draw alone (part of the shuffle)",
     lambda p: p["permutation draw alone (uniform numbers and their sort)"]),
    ("update: Adam step and the rest", lambda p: p[UPDATE] - p[CLIPPED] - p[GATHER]),
    ("rollout scan: policy forward and environment together",
     lambda p: p["rollout scan (policy forward and environment, 128 steps)"]),
    ("rollout: environment alone", lambda p: p["environment alone, 128 steps"]),
    ("rollout: policy forward alone", lambda p: p["policy forward alone, 128 steps"]),
    ("rollout: action noise", lambda p: p["action noise draw"]),
    ("critic pass after the rollout", lambda p: p["critic pass after the rollout"]),
    ("distillation forward, input statistics, whitening",
     lambda p: p["distillation forward, input statistics and whitening"]),
    ("reward filter, its statistics, advantage sums",
     lambda p: p["reward filter, its statistics and both advantage sums"]),
    ("rows put in per-policy order", lambda p: p["rows put in per-policy order (seven fields)"]),
    ("coverage map alone", lambda p: p["coverage map alone"]),
    ("episode log sums alone", lambda p: p["episode log sums alone"]),
)


def median(values: list) -> float:
    """The middle value of a list (the upper of the two middle values for an even count)."""
    return sorted(values)[len(values) // 2]


def card_name(record: dict) -> str:
    """The card's model as nvidia-smi names it: "NVIDIA RTX A4500, 20470 MiB, 580.1" -> "RTX A4500"."""
    return record["machine"]["card"].split(",")[0].replace("NVIDIA ", "").replace("GeForce ", "")


def where_measured(record: dict) -> str:
    """The Slurm job of a record, or its machine when there is no scheduler: "job 6873920"."""
    job = record["machine"]["slurm_job_id"]
    return f"job {job}" if job else f"{record['machine']['host']}, no scheduler"


def throughput_cells(t: dict) -> str:
    """The five throughput columns of one setting as table cells."""
    return (f"{t['copies']:,} | {t['seconds_per_iteration']:.4f} | "
            f"{t['total_steps_per_second_millions']:.2f} | "
            f"{t['steps_per_second_per_copy_thousands']:.1f} | "
            f"{t['hours_per_million_steps_per_copy']:.4f}")


THROUGHPUT_HEADER = ("policies<br>(copies) | seconds per<br>iteration | total steps per<br>second "
                     "(millions) | steps per second<br>per policy (thousands) | hours per million"
                     "<br>steps per policy")


def breakdown_tables() -> str:
    """One table per card and number of environments per policy, and one throughput table."""
    records = [json.loads(path.read_text()) for path in sorted((HERE / "time_breakdown").glob("*.json"))]
    groups = {}
    for record in records:
        groups.setdefault((card_name(record), record["envs_per_copy"]), []).append(record)
    out = ["# PointMaze Large: where the time of one training iteration goes", "",
           "Generated by `make_tables.py` from `time_breakdown/*.json`. Learner: the study's "
           "(clipped PPO, 4 epochs x 4 minibatches, 128-step rollouts, random network "
           "distillation, episode log and coverage map on); minibatches are gathered one epoch "
           "at a time at 128 environments per policy.", "",
           "- **Whole iteration:** the median over alternating rounds of chained calls with one "
           "wait at the end of a block, as a training loop runs.",
           "- **Each piece:** its own compiled function that returns all it computes, median "
           "over calls with a wait after each. A piece timed alone pays its own start and wait, "
           "so the pieces add up to more than the iteration.",
           "- **Share:** $\\dfrac{\\text{piece milliseconds}}{\\text{whole-iteration "
           "milliseconds}} \\times 100$, with the whole iteration timed one call at a time "
           "with a wait, as the pieces are.",
           "- **Episode log and coverage map, in the iteration:** the iteration as the study "
           "runs it minus the iteration built without that part, in milliseconds (chained "
           "calls, same process, alternating rounds).", ""]
    for (card, envs), group in sorted(groups.items(), key=lambda item: (item[0][1], item[0][0])):
        group.sort(key=lambda r: r["copies"])
        out += [f"## {envs} environments per policy, {card}", "",
                "| piece | " + " | ".join(f"ms at {r['copies']:,}<br>policies | share" for r in group) + " |",
                "|---|" + "---:|---:|" * len(group)]
        lines = {}
        for column, record in enumerate(group):
            pieces = {name: piece["median_seconds"] for name, piece in record["pieces"].items()}
            whole_wait = record["whole_iteration_one_call_with_wait_seconds"]
            rounds = record["whole_iteration_chained_seconds_per_round"]
            whole = median(rounds["as the study runs it"])
            lines.setdefault("**whole iteration, chained calls**", []).append(
                f"**{whole * 1e3:.2f}** | —")
            lines.setdefault("whole iteration, one call at a time with a wait", []).append(
                f"{whole_wait * 1e3:.2f} | 100%")
            for label, value in ROWS:
                try:
                    seconds = value(pieces)
                    cell = f"{seconds * 1e3:.2f} | {seconds / whole_wait * 100:.1f}%"
                except KeyError:
                    cell = "not measured | —"
                lines.setdefault(label, []).append(cell)
            for label, name in (("episode log, in the iteration", "without the episode log"),
                                ("coverage map, in the iteration", "without the coverage map")):
                difference = whole - median(rounds[name])
                lines.setdefault(label, []).append(
                    f"{difference * 1e3:+.2f} | {difference / whole * 100:+.1f}%")
        out += [f"| {label} | " + " | ".join(cells) + " |" for label, cells in lines.items()]
        out.append("")
    out += ["## Throughput of the whole iteration", "",
            "| card | environments<br>per policy | " + THROUGHPUT_HEADER + " |",
            "|---|---:|---:|---:|---:|---:|---:|"]
    for (card, envs), group in sorted(groups.items(), key=lambda item: (item[0][0], item[0][1])):
        for record in sorted(group, key=lambda r: r["copies"]):
            out.append(f"| {card} | {envs} | {throughput_cells(record['throughput'])} |")
    out += ["", "Measured in: " + ", ".join(sorted({where_measured(r) for r in records})) + ".", ""]

    # the same iteration at more policies per process, from the records of policies_per_process/
    scans = [json.loads(path.read_text())
             for path in sorted((HERE / "policies_per_process").glob("*.json"))]
    if scans:
        out += ["## Total steps per second against policies per process", "",
                "The study's iteration at 4 environments per policy (the production shape since "
                "2026-11-12 02:08 PT), one program per number of policies, chained calls. "
                "Doubling the policies is worth it while the total grows by 10% or more.", "",
                "| card | environments<br>per policy | " + THROUGHPUT_HEADER + " |",
                "|---|---:|---:|---:|---:|---:|---:|"]
        for record in scans:
            for shape in record["shapes"]:
                for arm in shape["arms"].values():
                    if "throughput" in arm:
                        out.append(f"| {card_name(record)} | {shape['envs_per_copy']} | "
                                   f"{throughput_cells(arm['throughput'])} |")
        out += ["", "Measured in: " + ", ".join(where_measured(r) for r in scans) + ".", ""]
    return "\n".join(out)


def idea_tables() -> str:
    """One table per idea record: every arm's five throughput columns and its paired ratio."""
    out = ["# PointMaze Large: paired timings of the speed ideas", "",
           "Generated by `make_tables.py` from `ideas/*.json`. All arms of a record are built in "
           "one process and timed in alternating rounds of chained iterations after two warm-up "
           "iterations each. The first arm is the reference.", "",
           "- **Ratio:** per round, $\\dfrac{\\text{reference seconds per iteration}}"
           "{\\text{arm seconds per iteration}}$, which is the arm's total steps per second "
           "relative to the reference; the table shows the median over the rounds, the least "
           "and the most, and in how many rounds the arm was faster.",
           "- An idea is kept only when the ratio is at least 1.05.", ""]
    for path in sorted((HERE / "ideas").glob("*.json")):
        record = json.loads(path.read_text())
        out += [f"## Idea {record['idea'].replace('_', ': ', 1).replace('-', ' ')}, "
                f"{card_name(record)} ({where_measured(record)})", ""]
        for shape in record["shapes"]:
            out += [f"{shape['envs_per_copy']} environments per policy, {shape['rounds']} "
                    "rounds" + ("" if shape.get("conclusive", False) else
                                " (**inconclusive: fewer than five rounds**)") + ":", "",
                    "| arm | " + THROUGHPUT_HEADER + " | ratio to the reference<br>(least to "
                    "most; rounds faster) |", "|---|---:|---:|---:|---:|---:|---|"]
            for name, arm in shape["arms"].items():
                if "throughput" not in arm:
                    continue
                out.append(f"| {name} | {throughput_cells(arm['throughput'])} | "
                           f"{arm['paired_ratio_median']:.3f} ({arm['paired_ratio_least']:.3f} "
                           f"to {arm['paired_ratio_most']:.3f}; "
                           f"{arm['rounds_faster_than_reference']} of {shape['rounds']}) |")
            if shape["not_measured"]:
                out.append("")
                out.append("Not measured inside the time limit: " + ", ".join(shape["not_measured"]) + ".")
            out.append("")
    return "\n".join(out)


