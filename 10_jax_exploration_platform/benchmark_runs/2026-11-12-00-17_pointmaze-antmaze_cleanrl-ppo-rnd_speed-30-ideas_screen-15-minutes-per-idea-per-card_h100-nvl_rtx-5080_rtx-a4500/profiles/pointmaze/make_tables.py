START = "<!-- pointmaze rows: start (generated by profiles/pointmaze/make_tables.py) -->"
END = "<!-- pointmaze rows: end -->"


def idea_records() -> dict:
    """idea number -> its records, one per card, in card order."""
    found = {}
    for path in sorted((HERE / "ideas").glob("*.json")):
        record = json.loads(path.read_text())
        found.setdefault(int(record["idea"].split("_")[0]), []).append(record)
    return found


def ledger_section() -> str:
    """The PointMaze part of the ledger: one row per idea, then every measurement's five columns."""
    records = idea_records()
    out = [START, "## PointMaze Large", "",
           "Generated from the records in `profiles/pointmaze/ideas/`; the per-idea tables with "
           "the rounds are in `profiles/pointmaze/idea_measurements.md`, the time breakdown in "
           "`profiles/pointmaze/time_breakdown.md`.", "",
           "- **Learner:** the study's (clipped PPO, 4 epochs x 4 minibatches, 128-step "
           "rollouts, random network distillation, episode log and coverage map on).",
           "- **Shapes:** 4 environments per policy with 512 policies (the production shape "
           "since 2026-11-12 02:08 PT; idea 25: 960 policies, the first sweep pass's 60 cells of "
           "16 seeds) and 16 environments per policy with 256 policies. The first measurements, "
           "made before that decision, are at 16 environments and at 128 environments with 64 "
           "policies (idea 25: 240 and 120 policies). On the RTX A4500 all these shapes use the "
           "card fully: four times the policies take 3.5 to 3.7 times the time.",
           "- **Gain:** the median over alternating rounds of $\\dfrac{\\text{reference seconds "
           "per iteration}}{\\text{idea seconds per iteration}}$, the idea's total steps per "
           "second relative to the reference built in the same process. An idea is kept at 1.05 "
           "or more.",
           "- **Risk:** same = identical results expected; dist = same distribution (rounding "
           "or random stream changes).", "",
           "| idea | what changed<br>(file, key) | risk | check and its result | gain per card "
           "and shape | kept |", "|---|---|---|---|---|---|"]
    measurements = []
    for number in ORDER:
        idea = IDEAS[number]
        gains = []
        for record in records.get(number, []):
            for shape in record["shapes"]:
                names = list(shape["arms"])
                for name in names:
                    arm = shape["arms"][name]
                    if "throughput" not in arm:
                        continue
                    measurements.append(
                        f"| {number} | {card_name(record)} | {shape['envs_per_copy']} | {name} | "
                        f"{throughput_cells(arm['throughput'])} |")
                    if name != names[0]:
                        label = f", {name}" if len(names) > 2 else ""
                        gains.append(f"{card_name(record)}, {shape['envs_per_copy']} "
                                     f"environments x {shape['copies']:,} policies{label}: "
                                     f"{arm['paired_ratio_median']:.3f}"
                                     + ("" if shape.get("conclusive", True) else
                                        " (inconclusive: fewer than five rounds)"))
        if number == 30:
            gains = ["see the time breakdown"]
        if number in ONE_ITERATION_ON_CARD:
            idea = dict(idea, check=idea["check"] + ". On the RTX 5080, one iteration from the "
                        "same state (job 6874102, where two builds of the reference are "
                        f"bit-identical): {ONE_ITERATION_ON_CARD[number]}")
        out.append(f"| {number}: {idea['name']} | {idea['change']} | {idea['risk']} | "
                   f"{idea['check']} | {'<br>'.join(gains) or 'not measured'} | {idea['kept']} |")
    out += ["", "### The five throughput columns of every measurement", "",
            "| idea | card | environments<br>per policy | arm | " + THROUGHPUT_HEADER + " |",
            "|---:|---|---:|---|---:|---:|---:|---:|---:|"] + measurements + ["", END, ""]
    return "\n".join(out)


def write_ledger() -> None:
    """Put the PointMaze part into the run folder's ledger, replacing an earlier copy of it.

    before: ledger.md absent, or holding other parts and perhaps an older PointMaze part
    after:  the same file with the current PointMaze part between its two marker lines
    """
    ledger = HERE.parent.parent / "ledger.md"
    section = ledger_section()
    if not ledger.exists():
        ledger.write_text("# Ledger of the speed ideas\n\nOne row per idea. Times are Pacific.\n\n"
                          + section)
        return
    text = ledger.read_text()
    if START in text:
        text = text[:text.index(START)] + section.rstrip("\n") + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + section
    ledger.write_text(text)


